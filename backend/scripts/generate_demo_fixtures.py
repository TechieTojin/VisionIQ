"""Generate demo-mode fixtures from REAL local YOLO inference.

The frontend's demo mode needs results to show when no backend is reachable.
Those results are produced HERE, by running the actual pipeline against real
images, and are then committed as static JSON.

This matters: the demo never invents detections. Every box, label and
confidence in the committed fixture came out of yolov8n on this machine. The
UI labels them as pre-recorded, because that is what they are.

Run (needs the 64-bit venv with torch):
    .venv\\Scripts\\python.exe scripts\\generate_demo_fixtures.py
"""

from __future__ import annotations

import io
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

BACKEND = Path(__file__).resolve().parent.parent
REPO = BACKEND.parent
PUBLIC = REPO / "frontend" / "public" / "demo"
FIXTURE = REPO / "frontend" / "src" / "demo" / "samples.json"

ASSETS = BACKEND / ".venv" / "Lib" / "site-packages" / "ultralytics" / "assets"


def synthetic_shelf() -> bytes:
    """A crude shelf scene.

    Generic COCO models typically find nothing here, which is exactly the
    case worth showing: the app says so plainly instead of inventing stock.
    """
    from PIL import Image, ImageDraw

    img = Image.new("RGB", (640, 480), (238, 236, 230))
    draw = ImageDraw.Draw(img)
    for shelf_y in (170, 330):
        draw.rectangle([0, shelf_y, 640, shelf_y + 10], fill=(150, 116, 78))
        for i in range(6):
            x = 30 + i * 100
            draw.rectangle([x, shelf_y - 90, x + 62, shelf_y], fill=(70, 120, 185))
            draw.rectangle([x + 18, shelf_y - 118, x + 44, shelf_y - 90], fill=(70, 120, 185))
    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=88)
    return buf.getvalue()


def main() -> int:
    from app.config import get_settings
    from app.services.analysis_service import analyse
    from app.services.image_analyzer import analyze_image

    settings = get_settings()
    if settings.detection_provider != "yolo":
        print("Set VISIONIQ_DETECTION_PROVIDER=yolo to generate real fixtures.")
        return 1

    sources: list[tuple[str, str, bytes]] = []
    for name, caption in (
        ("bus.jpg", "Street scene — several objects at a range of confidences"),
        ("zidane.jpg", "Two people — a sparser scene"),
    ):
        path = ASSETS / name
        if path.is_file():
            sources.append((name, caption, path.read_bytes()))
        else:
            print(f"  skip {name} (not found)")

    sources.append(
        (
            "synthetic_shelf.jpg",
            "Mock shelf — a generic model finds nothing here, and the app says so",
            synthetic_shelf(),
        )
    )

    PUBLIC.mkdir(parents=True, exist_ok=True)
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)

    samples = []
    for filename, caption, data in sources:
        print(f"running real inference on {filename} ...")
        metadata = analyze_image(filename, data)
        record = analyse(data, metadata, settings=settings, store_image=False)

        (PUBLIC / filename).write_bytes(data)

        payload = json.loads(record.model_dump_json())
        # Stable, obviously-fake identifiers so a demo record can never be
        # mistaken for a real stored analysis.
        payload["analysis_id"] = f"demo-{Path(filename).stem}"
        payload["owner_id"] = "demo"
        payload["execution_mode"] = "demo"
        payload["image_key"] = None

        detection = payload.get("detection") or {}
        samples.append(
            {
                "id": payload["analysis_id"],
                "filename": filename,
                "caption": caption,
                "image_url": f"/demo/{filename}",
                "record": payload,
            }
        )
        print(
            f"   -> {detection.get('detection_count', 0)} detections, "
            f"status={detection.get('status')}"
        )

    fixture = {
        "_comment": (
            "Generated by backend/scripts/generate_demo_fixtures.py from REAL "
            "yolov8n inference. These are pre-recorded results, not live "
            "inference, and the UI labels them as such. Do not hand-edit."
        ),
        "model": samples[0]["record"]["detection"]["model"] if samples else None,
        "samples": samples,
    }
    FIXTURE.write_text(json.dumps(fixture, indent=2), encoding="utf-8")

    print(f"\nwrote {FIXTURE.relative_to(REPO)}")
    print(f"wrote {len(samples)} images to {PUBLIC.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
