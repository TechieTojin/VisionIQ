import type { InsightsResult, RetailIntelligence } from '../types'

interface InsightsPanelProps {
  insights: InsightsResult
  retail: RetailIntelligence
}

const SOURCE_LABEL: Record<string, string> = {
  rules: 'Deterministic',
  bedrock: 'AI generated',
  unavailable: 'Unavailable',
}

export function InsightsPanel({ insights, retail }: InsightsPanelProps) {
  return (
    <div className="panel">
      <div className="panel__header">
        <h2>Observations</h2>
        <span
          className={`badge badge--${
            insights.source === 'bedrock' ? 'ai' : 'neutral'
          }`}
          title={
            insights.source === 'rules'
              ? 'Generated from detection counts only — no language model involved.'
              : 'Generated by a language model from detection counts.'
          }
        >
          {SOURCE_LABEL[insights.source] ?? insights.source}
        </span>
      </div>

      <p className="summary">{insights.summary}</p>

      {insights.degraded && (
        <p className="notice notice--warn">
          The AI narrator was unavailable; these are deterministic summaries.
        </p>
      )}

      {insights.observations.length > 0 && (
        <ul className="bullets">
          {insights.observations.map((o, i) => (
            <li key={i}>{o.text}</li>
          ))}
        </ul>
      )}

      {insights.suggested_actions.length > 0 && (
        <>
          <h3 className="subhead">Suggested actions</h3>
          <ul className="bullets">
            {insights.suggested_actions.map((a, i) => (
              <li key={i}>{a}</li>
            ))}
          </ul>
        </>
      )}

      <h3 className="subhead">Reliability</h3>
      <dl className="facts">
        <div>
          <dt>SKU recognition</dt>
          <dd>
            <span className="badge badge--warn">{retail.sku.status}</span>
          </dd>
        </div>
        <div>
          <dt>Shelf-gap detection</dt>
          <dd>
            <span className="badge badge--warn">
              {retail.shelf_gaps.reliability}
            </span>
          </dd>
        </div>
        <div>
          <dt>Occupancy estimate</dt>
          <dd>
            {retail.occupancy.covered_fraction !== null ? (
              <>
                {Math.round(retail.occupancy.covered_fraction * 100)}%{' '}
                <span className="badge badge--warn">
                  {retail.occupancy.reliability}
                </span>
              </>
            ) : (
              <span className="badge badge--warn">not available</span>
            )}
          </dd>
        </div>
      </dl>

      {retail.caveats.length > 0 && (
        <details className="caveats">
          <summary>Limitations ({retail.caveats.length})</summary>
          <ul className="bullets">
            {retail.caveats.map((c, i) => (
              <li key={i}>{c}</li>
            ))}
          </ul>
        </details>
      )}

      <p className="disclaimer">{insights.disclaimer}</p>
    </div>
  )
}
